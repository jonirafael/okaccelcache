import type { Prisma } from '@prisma/client'

/**
 * Same three fields Accelerate documents for `cacheStrategy`.
 * `ttl` and `swr` are seconds. See the README for how this package interprets omissions.
 */
export interface CacheStrategy {
  /**
   * Seconds a stored result is served as fresh, without querying the database.
   * Omitted means 0.
   */
  ttl?: number
  /**
   * Extra seconds after `ttl` during which a stale result is returned immediately
   * while a refresh runs in the background. Omitted means 0.
   */
  swr?: number
  /**
   * Tags used later with `$accelerate.invalidate`.
   * Each tag is alphanumeric or underscore, 1–64 characters, at most five tags.
   */
  tags?: readonly string[]
}

/**
 * Metadata returned by `.withAccelerateInfo()`.
 *
 * `cacheStatus`, `lastModified`, `region`, `requestId`, and `signature` use the
 * same names as Accelerate. `region` is always `"local"`. `requestId` and
 * `signature` are generated by this package, not by Cloudflare.
 */
export interface AccelerateInfo {
  cacheStatus: 'ttl' | 'swr' | 'miss' | 'none'
  lastModified: Date
  region: string
  requestId: string
  signature: string
}

export interface AccelerateInvalidateResult {
  requestId: string
}

/**
 * A Prisma read that can also report cache metadata.
 * The runtime value is still Prisma's own promise, so `$transaction([query])` can accept it.
 * Relation fluent helpers such as `findUnique().posts()` are not part of this type.
 */
export interface AcceleratePromise<T> extends Prisma.PrismaPromise<T> {
  withAccelerateInfo(): Prisma.PrismaPromise<{
    data: T
    info: AccelerateInfo
  }>
}

export interface NormalizedStrategy {
  ttlMs: number
  swrMs: number
  tags: readonly string[]
}

/** One cached query result plus the invalidation generations it was written with. */
export interface StoredEntry {
  payload: string
  storedAt: number
  ttlMs: number
  swrMs: number
  /** Epoch milliseconds on the extension clock. The entry is a miss at and after this time. */
  hardExpireAt: number
  tags: readonly string[]
  tagGenerations: Readonly<Record<string, number>>
  allGeneration: number
}

export interface CacheRead {
  entry: StoredEntry | null
  allGeneration: number
  /**
   * Current generation of every tag passed to `read` and every tag stored on the entry.
   * A tag that has never been invalidated is generation 0.
   */
  tagGenerations: Readonly<Record<string, number>>
}

/**
 * Backend for cached Prisma reads.
 *
 * Tag invalidation is generation-based so it works across processes:
 * `invalidateTags` / `invalidateAll` bump a counter, and a later `read` returns
 * that counter. The extension treats an entry as missing when a current
 * generation is greater than the generation stored on the entry.
 *
 * `read` must include generations for the requested tags and for any tags
 * already saved on the entry. It must not hide invalidated entries; the
 * extension decides. It may drop entries whose `hardExpireAt` has passed
 * according to its own clock, but the extension also checks `hardExpireAt`
 * with the clock passed to `withOkAccelCache`.
 */
export interface CacheStore {
  read(key: string, tags: readonly string[]): Promise<CacheRead>
  write(key: string, entry: StoredEntry): Promise<void>
  invalidateTags(tags: readonly string[]): Promise<void>
  invalidateAll(): Promise<void>
  /**
   * Best-effort cross-process lock used to collapse stale-while-revalidate refreshes.
   * Return false when another holder already has the lock.
   * The lock must release itself after `ttlMs` even if the holder crashes.
   */
  tryLock?(key: string, ttlMs: number): Promise<boolean>
}

export interface OkAccelCacheOptions {
  /** Where entries live. Defaults to an in-memory LRU store. */
  store?: CacheStore
  /**
   * Capacity of the default in-memory store.
   * Ignored when `store` is set.
   * @default 1000
   */
  maxEntries?: number
  /**
   * Clock in epoch milliseconds. Defaults to `Date.now`.
   * Redis key eviction still uses the wall clock as a backstop.
   */
  now?: () => number
  /**
   * Namespace included in cache keys.
   * When you use a Redis store, set the same prefix on the store so
   * `invalidateAll` can delete that store's entry keys.
   * @default "okaccelcache"
   */
  keyPrefix?: string
  /**
   * A stale response was already returned, then the background refresh failed.
   * Defaults to `console.error`.
   */
  onBackgroundError?: (error: unknown, info: BackgroundErrorInfo) => void
  /**
   * The store threw while reading or writing. The query still runs against the database.
   * Defaults to `console.error`.
   */
  onStoreError?: (error: unknown, info: StoreErrorInfo) => void
}

export interface BackgroundErrorInfo {
  model?: string
  operation: string
  key: string
}

export interface StoreErrorInfo extends BackgroundErrorInfo {
  op: 'read' | 'write'
}
